// Checks whether every segment of prefix matches the start of key
function isPrefixOf(prefix: QueryKey, key: QueryKey): boolean {
  return prefix.length <= key.length && prefix.every((part, index) => part === key[index]);
}

// Invalidates every query root that reads any of the written tables, once per root, across all workspaces
export function invalidateWrites(queryClient: QueryClient, tables: readonly Table[]): void {
  const unique = new Map<string, QueryKey>();
  for (const table of tables) {
    for (const key of READERS[table]) unique.set(JSON.stringify(key), key);
  }
  const keys = [...unique.values()];
  for (const key of keys) {
    const covered = keys.some((other) => other.length < key.length && isPrefixOf(other, key));
    if (!covered) queryClient.invalidateQueries({ queryKey: key });
  }
}
